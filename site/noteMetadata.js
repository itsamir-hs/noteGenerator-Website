// Extracts note metadata from either a freshly rendered note or a pre-rendered
// HTML file, so both sources feed the home page with identical data.

import { SITE_CONFIG } from "./config.js";
import { toPlainText, toSingleLine, normalizeSearchText } from "./textUtils.js";

const METADATA_LABELS = [
    "courseName",
    "topic",
    "instructor",
    "sessionDate",
    "generatedDate"
];

const MAX_SUMMARY_LENGTH = 220;

function emptyMetadata() {
    return {
        courseName: "",
        topic: "",
        instructor: "",
        sessionDate: "",
        generatedDate: ""
    };
}

/** Truncate plain text on a word boundary and append an ellipsis. */
export function createSummary(value, maxLength = MAX_SUMMARY_LENGTH) {
    const text = toSingleLine(value);

    if (text.length <= maxLength) {
        return text;
    }

    const truncated = text.slice(0, maxLength);
    const lastSpace = truncated.lastIndexOf(" ");

    return `${(lastSpace > maxLength * 0.6 ? truncated.slice(0, lastSpace) : truncated).trimEnd()}…`;
}

/** Metadata straight from `renderNoteHtml`'s return value. */
export function extractRenderedNoteMetadata(renderedNote) {
    const metadata = emptyMetadata();

    for (const key of METADATA_LABELS) {
        const value = renderedNote?.metadata?.[key];

        if (typeof value === "string" && value.trim()) {
            metadata[key] = toSingleLine(value);
        }
    }

    return {
        title: toSingleLine(renderedNote?.title) || "بدون عنوان",
        metadata,
        headings: (renderedNote?.tocItems ?? [])
            .filter((item) => item.level === 2)
            .map((item) => toPlainText(item.title)),
        theme: null
    };
}

/** The note body of a rendered document, without header/sidebar/modals. */
function extractNoteContainer(html) {
    const source = String(html);
    const start = source.indexOf('<main class="noteContainer">');

    return start === -1 ? source : source.slice(start);
}

/** Metadata from an already-rendered HTML document.
 *
 * `templates/note.html` renders the five metadata values as
 * `<span class="metadataValue">…</span>` in a fixed order, so the values are read
 * positionally — that keeps this working for notes generated by older builds.
 */
export function extractPreRenderedMetadata(html) {
    const titleMatch = String(html).match(/<title>([\s\S]*?)<\/title>/i);
    const title = toSingleLine(toPlainText(titleMatch?.[1] ?? ""));

    const values = [];
    const valuePattern = /<span class="metadataValue">([\s\S]*?)<\/span>/g;

    for (const match of String(html).matchAll(valuePattern)) {
        values.push(toSingleLine(toPlainText(match[1])));
    }

    const metadata = emptyMetadata();

    METADATA_LABELS.forEach((key, index) => {
        const value = values[index];

        if (value) {
            metadata[key] = value;
        }
    });

    const headings = [];

    // Only the note body: the sidebar ("فهرست مطالب"), the sticky-note panel and
    // the About modal also contain <h2> elements that are not note sections.
    for (const match of extractNoteContainer(html).matchAll(
        /<h2[^>]*>([\s\S]*?)<\/h2>/g
    )) {
        const heading = toSingleLine(toPlainText(match[1]));

        if (heading) {
            headings.push(heading);
        }
    }

    const themeMatch = String(html).match(/<html[^>]*\sdata-theme="([^"]*)"/);

    const introductionText = extractFirstParagraphs(html);

    return {
        title: title || "بدون عنوان",
        metadata,
        headings,
        theme: themeMatch ? themeMatch[1] : null,
        summarySource: introductionText
    };
}

/** Text of the first few paragraphs of the note body, used as a summary. */
function extractFirstParagraphs(html) {
    const containerStart = String(html).indexOf('<section class="noteSection introductionSection">');
    const body = containerStart === -1 ? String(html) : String(html).slice(containerStart);

    const paragraphs = [];

    for (const match of body.matchAll(/<p>([\s\S]*?)<\/p>/g)) {
        const text = toSingleLine(toPlainText(match[1]));

        if (text.length > 20) {
            paragraphs.push(text);
        }

        if (paragraphs.length >= 3) {
            break;
        }
    }

    return paragraphs.join(" ");
}

/**
 * Merge extracted metadata with the registry override and derive everything the
 * home page needs.
 */
export function buildNoteEntry({
    slug,
    sourceKind,
    sourceFile,
    extracted,
    registryEntry,
    order
}) {
    const title = registryEntry.title || extracted.title;
    const course = registryEntry.course || extracted.metadata.courseName || "";
    const topic = registryEntry.topic || extracted.metadata.topic || "";
    const instructor = registryEntry.instructor || extracted.metadata.instructor || "";
    const sessionDate = registryEntry.sessionDate || extracted.metadata.sessionDate || "";
    const generatedDate = registryEntry.generatedDate || extracted.metadata.generatedDate || "";
    const featured = registryEntry.featured ?? false;
    const hidden = registryEntry.hidden ?? false;

    const description = createSummary(
        registryEntry.description ||
            topic ||
            course ||
            extracted.summarySource ||
            extracted.headings.slice(0, 3).join(" — ")
    );

    const searchText = normalizeSearchText(
        [
            title,
            course,
            topic,
            instructor,
            sessionDate,
            generatedDate,
            description,
            extracted.headings.join(" ")
        ]
            .filter(Boolean)
            .join(" ")
    );

    return {
        slug,
        title,
        description,
        course,
        topic,
        instructor,
        sessionDate,
        generatedDate,
        headings: extracted.headings,
        theme: extracted.theme || SITE_CONFIG.defaultTheme,
        featured,
        hidden,
        order: registryEntry.order ?? order,
        source: {
            kind: sourceKind,
            file: sourceFile
        },
        url: `notes/${slug}/`,
        searchText
    };
}